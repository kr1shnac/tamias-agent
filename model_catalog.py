"""The model catalog: real, priced, tool-capable models from the provider.

`models/catalog.json` is generated by `demo/fetch_models.py` from the provider's
public `/models` endpoint. This module is the only thing that reads it, so the
rest of the code never parses JSON and a missing/broken catalog degrades to an
empty list instead of a crash.

Nothing here makes a network call. Prices are the provider's list prices
(USD per 1k tokens); they are used for the *hypothetical* premium-equivalent
comparison in the UI, never presented as measured savings.
"""
from __future__ import annotations

import json
import os

CATALOG_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "models", "catalog.json")

TIERS = ("free", "mid", "premium")

# A rotation demo's *first* turn is the one people judge, so it starts on the
# model this repo already ships as its default. The second is the other model
# the live gate rehearses, so the first switch in a demo is a proven one too.
PREFERRED_FIRST = (
    "nvidia/nemotron-3.5-lightning:free",
    "nvidia/nemotron-3-ultra-550b-a55b:free",
)

_cache: dict | None = None


def load(path: str | None = None) -> dict:
    """Load and cache the catalog. A missing or invalid file yields an empty one."""
    global _cache
    target = path or CATALOG_PATH
    if _cache is not None and path is None:
        return _cache
    try:
        with open(target, encoding="utf-8") as handle:
            data = json.load(handle)
        if not isinstance(data.get("models"), list):
            raise ValueError("catalog has no 'models' list")
    except Exception:
        data = {"models": [], "counts": {}, "error": f"unreadable: {target}"}
    if path is None:
        _cache = data
    return data


def models(tier: str | None = None) -> list[dict]:
    """Every catalog entry, or only one tier's, in catalog order."""
    entries = list(load().get("models") or [])
    if tier is None:
        return entries
    return [m for m in entries if m.get("tier") == tier]


def ids(tier: str | None = None) -> list[str]:
    return [m["id"] for m in models(tier)]


def by_id(model_id: str) -> dict | None:
    for model in models():
        if model.get("id") == model_id:
            return model
    return None


def tier_of(model_id: str) -> str:
    """Catalog tier for an id; anything unknown but ':free' counts as free."""
    entry = by_id(model_id)
    if entry:
        return entry.get("tier", "free")
    return "free" if str(model_id).endswith(":free") else "paid"


def pool(tier: str = "free", limit: int | None = None) -> list[str]:
    """Model ids for rotation. Defaults to the free tier: a demo must be $0."""
    chosen = ids(tier)

    if tier == "free":
        head = [m for m in PREFERRED_FIRST if m in chosen]
        chosen = head + [m for m in chosen if m not in head]

    return chosen[:limit] if limit else chosen


def pick(index: int, tier: str = "free", limit: int | None = None) -> str | None:
    """Deterministically pick the model for turn/step ``index`` from the pool."""
    chosen = pool(tier, limit)
    if not chosen:
        return None
    return chosen[index % len(chosen)]


def counts() -> dict:
    return dict(load().get("counts") or {})


def fetched_at() -> str:
    return str(load().get("fetched") or "unknown")


def label(model_id: str) -> str:
    """Short human label: the model's name without the provider prefix."""
    entry = by_id(model_id)
    if entry:
        return str(entry.get("name") or model_id).split(":")[0].strip()
    return model_id


def price_note(model_id: str) -> str:
    entry = by_id(model_id)
    if not entry:
        return "price unknown"
    prompt = entry.get("prompt_usd_per_1k", 0.0)
    completion = entry.get("completion_usd_per_1k", 0.0)
    if prompt == 0 and completion == 0:
        return "free"
    return f"${prompt:.6f}/1k in · ${completion:.6f}/1k out"


def summary_lines() -> list[str]:
    """A few lines describing the catalog, for a demo header."""
    data = counts()
    return [
        f"{data.get('total', 0)} models, all tool-capable "
        f"(from {data.get('available_with_tools', '?')} available)",
        f"free {data.get('free', 0)} · mid {data.get('mid', 0)} · "
        f"premium {data.get('premium', 0)}",
        f"prices fetched {fetched_at()}",
    ]
